class Topology():
    """ 
    This class contains information about the topology, e.g. which bonds, angles and dihedrals are in the system.
    """

    def __init__(self, molecule_names=None):
        self.bonds = []
        self.angles = []
        self.dihedrals = []
        self.molecules = {}
        if molecule_names:
            for molecule_name in molecule_names:
                self.add_molecule_name(molecule_name)

    def add_molecule_name(self, name: str):
        self.molecules[name] = []

    # def read()
    # def write__to_hdf5()
    # ...

    def save(self, h5group):
        h5group.create_dataset('bonds', data=self.bonds, dtype=np.int32 )
        h5group.create_dataset('angles', data=self.angles, dtype=np.int32 )
        h5group.create_dataset('dihedrals', data=self.dihedrals, dtype=np.int32 )

        h5group.create_group('molecules')
        h5group['molecules'].attrs['names'] = list(self.molecules.keys()) # list of names of molecule types
        for key in self.molecules.keys():
            h5group['molecules'].create_dataset(key, data=self.molecules[key], dtype=np.int32)
        return 
   
    def from_h5(self, h5group):
        self.bonds = h5group['bonds'][:].tolist()
        self.angles = h5group['angles'][:].tolist()
        self.dihedrals = h5group['dihedrals'][:].tolist()
        molecule_keys = list(h5group['molecules'].keys())
        self.molecules = {}
        for key in molecule_keys:
            self.molecules[key] = h5group['molecules'][key][:].tolist()

        return 

def bonds_from_positions(positions, cut_off, bond_type):
    """
    Identify atom pairs within a specified distance threshold to define bonds.

    This function performs a pairwise distance check between all atoms in the 
    system. A bond is created if the Euclidean distance between two atoms 
    is less than or equal to the provided cutoff. 
    
    The function uses a brute-force $O(N^2)$ approach. Therefore, it is advised to 
    use it on individual molecules before using :func'replicate_molecules' or for small systems.

    Parameters
    ----------
    positions : array_like
        An $N \times D$ array or list of coordinates representing atom positions.
    cut_off : float
        The maximum radial distance within which two atoms are considered 
        to be bonded.
    bond_type : int or str
        A label or identifier assigned to every bond generated by this search.

    Returns
    -------
    list of lists
        A list of bond definitions, where each element is [index_j, index_i, bond_type].
        Note that index_j < index_i to prevent duplicate or self-bonding.

    See also
    --------

    :class:`gamdpy.Bonds`
    """
    
    bonds = []
    for i in range(len(positions)):
        for j in range(i):
            squared_distance = np.sum( (np.array(positions[j]) - np.array(positions[i]))**2 )
            if squared_distance <= cut_off**2:
                bonds.append([j, i, bond_type])
    return bonds

def angles_from_bonds(bonds, angle_type):
    """
    Identifies and generates a list of angles from a given set of bonds.

    This function performs a combinatorial search through the bond list to 
    identify pairs of bonds that share a common atom (vertex). For every 
    connected pair found, it records the three-atom sequence forming the angle.

    Parameters
    ----------
        bonds (list of list/tuple): A list where each element represents a 
            bond as a pair of atom indices (e.g., [[0, 1, ..], [1, 2, ...]]).
            Further entries beyond the two atom indices (eg. bond type) is
            ignored.
        angle_type (any): A label or parameter defining the type of angle 
            to be assigned to the detected triplets.

    Returns:
    -------
        list of list: A list of detected angles. Each entry contains:
            - The index of the first outer atom.
            - The index of the shared central atom (vertex).
            - The index of the second outer atom.
            - The provided `angle_type`.

     See also
    --------

    :class:`gamdpy.Angles`

    """
    angles = []
    for bond_index, bond in enumerate(bonds):
        for other_bond in bonds[bond_index+1:]:
            if bond[0] == other_bond[0]: 
                angles.append([bond[1], bond[0], other_bond[1], angle_type])
            elif bond[0] == other_bond[1]: 
                angles.append([bond[1], bond[0], other_bond[0], angle_type])
            elif bond[1] == other_bond[0]: 
                angles.append([bond[0], bond[1], other_bond[1], angle_type])
            elif bond[1] == other_bond[1]: 
                angles.append([bond[0], bond[1], other_bond[0], angle_type])        
    return angles

def dihedrals_from_angles(angles, dihedral_type):
    """
    Construct dihedral definitions by joining overlapping bond angles.

    Identifies sequences of four atoms that form a torsion angle by 
    finding pairs of three-atom angles that share a common central bond. 
    The function accounts for various atom orderings within the angle 
    definitions to ensure all contiguous chains are captured.

    Parameters
    ----------
    angles : list of list of int
        A collection of angles, where each angle is defined by three 
        atom indices (e.g., [atom1, atom2, atom3]).
        Further entries beyond the three atom indices (eg. angle type) is
        ignored.
    dihedral_type : int, str, or float
        The parameter or type identifier to be assigned to the 
        resulting dihedral definitions.

    Returns
    -------
    dihedrals : list of list
        A list of dihedrals, where each element is a list containing 
        four atom indices and the specified dihedral type:
        [atom1, atom2, atom3, atom4, dihedral_type].

    See Also
    --------
    :class:`gamdpy.Dihedrals`

    Notes
    -----
    A dihedral is formed when two angles, i-j-k and j-k-l, share the 
    central bond j-k. Because angles can be defined in either direction 
    (i-j-k or k-j-i), this function checks four permutations of atom 
    connectivity to correctly sequence the four-atom chain.
    """

    dihedrals = []
    for angle_index, angle in enumerate(angles):
        for other_angle in angles[angle_index+1:]:
            if angle[1] == other_angle[0] and angle[2] == other_angle[1]: 
                dihedrals.append([angle[0], angle[1], angle[2], other_angle[2], dihedral_type])
            elif angle[1] == other_angle[2] and angle[2] == other_angle[1]: 
                dihedrals.append([angle[0], angle[1], angle[2], other_angle[0], dihedral_type])
            elif angle[1] == other_angle[0] and angle[0] == other_angle[1]: 
                dihedrals.append([angle[2], angle[1], angle[0], other_angle[2], dihedral_type])
            elif angle[1] == other_angle[2] and angle[0] == other_angle[1]: 
                dihedrals.append([angle[2], angle[1], angle[0], other_angle[0], dihedral_type])
            
    return dihedrals


def molecules_from_bonds(bonds):
    """
    Identify and group connected molecular components with sorted indices.

    This function processes a list of bonds to find connected components (molecules).
    It ensures that the atom indices within each resulting molecule are returned 
    in ascending order, providing a deterministic output.

    Parameters
    ----------
    bonds : list of list
        A list of bonds where each bond is [atom1, atom2, ...]. 
        Additional metadata beyond the first two elements is ignored.

    Returns
    -------
    molecules : list of list of int
        A list of molecules, where each inner list contains unique, 
        sorted atom indices belonging to that connected component.
        The list of molecules is sorted by the index of first atom 
        for each molecule.

    Examples
    --------
    >>> bonds = [[5, 4], [3, 2, 'single'], [1, 0, 'single'], [2, 1, 'double']]
    >>> molecules_from_bonds(bonds)
    [[0, 1, 2, 3], [4, 5]]
    """

    # Initialize molecules as sorted pairs from bonds
    molecules = [sorted([bond[0], bond[1]]) for bond in bonds]
    initial_num_molecules = len(molecules)
    
    for index1 in range(initial_num_molecules - 1, 0, -1): 
        for index2 in range(index1):
            # Check for connectivity
            if not set(molecules[index1]).isdisjoint(molecules[index2]):
                # Merge, remove duplicates, and sort
                molecules[index2] = sorted(set(molecules[index1]).union(molecules[index2]))
                molecules.pop(index1)
                break
                
    return sorted(molecules, key=lambda x: x[0])


